// A simple arena block structure.
//
// Measurements with standard library modules suggest the average
// allocation is about 20 bytes and that most compilers use a single
// block.
#[repr(C)]
#[derive(Clone, Copy)]
struct _block {
    /// Total number of bytes owned by this block available to pass out.
    /// Read-only after initialization.  The first such byte starts at
    /// ab_mem.
    ab_size: u64,
    /// Total number of bytes already passed out.  The next byte available
    /// to pass out starts at ab_mem + ab_offset.
    ab_offset: u64,
    /// An arena maintains a singly-linked, NULL-terminated list of
    /// all blocks owned by the arena.  These are linked via the
    /// ab_next member.
    ab_next: *mut _block,
    /// Pointer to the first allocatable byte owned by this block.  Read-
    /// only after initialization.
    ab_mem: *mut (),
}

// The arena manages two kinds of memory, blocks of raw memory
// and a list of PyObject* pointers.  PyObjects are decrefed
// when the arena is freed.
#[repr(C)]
#[derive(Clone, Copy)]
struct _arena {
    /// Pointer to the first block allocated for the arena, never NULL.
    /// It is used only to find the first block when the arena is
    /// being freed.
    a_head: *mut _block,
    /// Pointer to the block currently used for allocation.  Its
    /// ab_next field should be NULL.  If it is not-null after a
    /// call to block_alloc(), it means a new block has been allocated
    /// and a_cur should be reset to point it.
    a_cur: *mut _block,
    /// A Python list object containing references to all the PyObject
    /// pointers associated with this arena.  They will be DECREFed
    /// when the arena is freed.
    a_objects: *mut _object,
}

fn block_new(size: u64) -> *mut _block {
    // Allocate header and block as one unit.
    // ab_mem points just past header.
    let b: *mut _block =
        (unsafe { PyMem_Malloc((core::mem::size_of::<_block>() as u64).wrapping_add(size)) })
            as *mut _block;
    if b.is_null() {
        return core::ptr::null_mut::<_block>();
    }
    unsafe {
        (*b).ab_size = size;
    }
    unsafe {
        (*b).ab_mem = b.wrapping_offset(1 as isize) as *mut ();
    }
    unsafe {
        (*b).ab_next = core::ptr::null_mut::<_block>();
    }
    unsafe {
        (*b).ab_offset = ((_Py_ALIGN_UP!(unsafe { (*b).ab_mem }, 8i32) as *mut i8)
            .offset_from((*b).ab_mem as *mut i8) as i64) as u64;
    }
    b
}

fn block_free(mut b: *mut _block) {
    while !b.is_null() {
        let next: *mut _block = unsafe { (*b).ab_next };
        unsafe { PyMem_Free(b as *mut ()) };
        b = next;
    }
}

fn block_alloc(mut b: *mut _block, mut size: u64) -> *mut () {
    size = _Py_SIZE_ROUND_UP!(size, 8i32);
    if unsafe { (*b).ab_offset }.wrapping_add(size) > unsafe { (*b).ab_size } {
        // If we need to allocate more memory than will fit in
        // the default block, allocate a one-off block that is
        // exactly the right size.
        let newbl: *mut _block = block_new(if size < 8192 { 8192u64 } else { size });
        if newbl.is_null() {
            return core::ptr::null_mut::<()>();
        }
        unsafe {
            (*b).ab_next = newbl;
        }
        b = newbl;
    }
    let p: *mut () = ((unsafe { (*b).ab_mem }) as *mut i8)
        .wrapping_offset((unsafe { (*b).ab_offset }) as isize) as *mut ();
    let __v1: u64 = unsafe { (*b).ab_offset };
    unsafe {
        (*b).ab_offset = __v1.wrapping_add(size);
    }
    p
}

#[unsafe(no_mangle)]
extern "C-unwind" fn _PyArena_New() -> *mut _arena {
    let arena: *mut _arena =
        (unsafe { PyMem_Malloc(core::mem::size_of::<_arena>() as u64) }) as *mut _arena;
    if arena.is_null() {
        return (unsafe { PyErr_NoMemory() }) as *mut _arena;
    }
    unsafe {
        (*arena).a_head = block_new(8192u64);
    }
    unsafe {
        (*arena).a_cur = (*arena).a_head;
    }
    if unsafe { (*arena).a_head }.is_null() {
        unsafe { PyMem_Free(arena as *mut ()) };
        return (unsafe { PyErr_NoMemory() }) as *mut _arena;
    }
    unsafe {
        (*arena).a_objects = PyList_New(0i64);
    }
    if unsafe { (*arena).a_objects }.is_null() {
        block_free(unsafe { (*arena).a_head });
        unsafe { PyMem_Free(arena as *mut ()) };
        return (unsafe { PyErr_NoMemory() }) as *mut _arena;
    }
    arena
}

