/// Free a tok_state structure
#[unsafe(no_mangle)]
extern "C-unwind" fn _PyTokenizer_Free(tok: *mut tok_state) {
    if !unsafe { (*tok).encoding }.is_null() {
        unsafe { PyMem_Free((*tok).encoding as *mut ()) };
    }
    Py_XDECREF!(unsafe { (*tok).decoding_readline });
    Py_XDECREF!(unsafe { (*tok).decoding_buffer });
    Py_XDECREF!(unsafe { (*tok).readline });
    Py_XDECREF!(unsafe { (*tok).filename });
    if (!unsafe { (*tok).readline }.is_null() || !unsafe { (*tok).fp }.is_null())
        && !unsafe { (*tok).buf }.is_null()
    {
        unsafe { PyMem_Free((*tok).buf as *mut ()) };
    }
    if !unsafe { (*tok).input }.is_null() {
        unsafe { PyMem_Free((*tok).input as *mut ()) };
    }
    if !unsafe { (*tok).interactive_src_start }.is_null() {
        unsafe { PyMem_Free((*tok).interactive_src_start as *mut ()) };
    }
    unsafe { PyMem_Free(tok as *mut ()) };
}

